"""Shell completion scripts, generated from the argparse parser."""

from __future__ import annotations

import argparse

SHELLS = ("bash",)


def _subcommands(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def _options(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in parser._actions if a.option_strings]


def bash_script(parser: argparse.ArgumentParser) -> str:
    """A bash completion script for ``sudokit``: commands, options, choices."""
    subs = _subcommands(parser)
    lines = [
        "# bash completion for sudokit (generated by `sudokit completion bash`)",
        "_sudokit() {",
        "    local cur prev cmd",
        "    COMPREPLY=()",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '    cmd="${COMP_WORDS[1]}"',
        "    if [ \"$COMP_CWORD\" -eq 1 ]; then",
        f'        COMPREPLY=( $(compgen -W "{" ".join(subs)} --help --version" -- "$cur") )',
        "        return 0",
        "    fi",
        '    case "$cmd:$prev" in',
    ]
    for name, sub in subs.items():
        for action in _options(sub):
            if action.choices:
                flags = "|".join(f"{name}:{o}" for o in action.option_strings)
                lines.append(f"        {flags})")
                lines.append(f'            COMPREPLY=( $(compgen -W "{" ".join(map(str, action.choices))}" -- "$cur") )')
                lines.append("            return 0 ;;")
    lines += ["    esac", '    case "$cmd" in']
    for name, sub in subs.items():
        flags = " ".join(o for a in _options(sub) for o in a.option_strings)
        lines.append(f"        {name})")
        lines.append(f'            if [[ "$cur" == -* ]]; then COMPREPLY=( $(compgen -W "{flags}" -- "$cur") ); fi ;;')
    lines += ["    esac", "    return 0", "}", "complete -o default -F _sudokit sudokit", ""]
    return "\n".join(lines)
